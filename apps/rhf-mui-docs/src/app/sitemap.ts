import { readdirSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { MetadataRoute } from 'next';
import { websiteUrl } from '@/constants';
import lastmodMap from '@/generated/sitemap-lastmod.json';

const APP_DIR = join(process.cwd(), 'src', 'app');
const PAGE_RE = /^page\.(mdx|tsx|jsx|ts|js)$/;

/* Older doc versions are intentionally kept out of the sitemap. */
const EXCLUDE_RE = /^v[1-9]\d*(\/|$)/;

type SiteMapRecord = { route: string };

/** Recursively collect the route path of every page.* under src/app. */
function collectRoutes(dir: string): SiteMapRecord[] {
  const out: SiteMapRecord[] = [];

  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    /* skip route groups "(x)" and private "_x" folders */
    const isSkippedDir = entry.name.startsWith('(') || entry.name.startsWith('_');
    if (entry.isDirectory() && !isSkippedDir) {
      out.push(...collectRoutes(full));
    } else if (!entry.isDirectory() && PAGE_RE.test(entry.name)) {
      const rel = relative(APP_DIR, dir).split(sep).join('/');
      if (!rel || !EXCLUDE_RE.test(rel)) {
        out.push({ route: rel ? `/${rel}` : '/' });
      }
    }
  }
  return out;
}

function priorityFor(route: string): number {
  if (route === '/') {
    return 1;
  }
  return route.split('/').length === 2 ? 0.8 : 0.6;
}

/*
 * `lastModified` per route comes from `src/generated/sitemap-lastmod.json`
 * (each page's last git author date, including its props table / demo form),
 * regenerated by `scripts/gen-sitemap-lastmod.mjs`, which `dev` and `build` run
 * first. That keeps fs/git access out of the app bundle, and avoids file mtimes
 * and build timestamps, which would mark every URL modified on every deploy.
 *
 * Home is the slash-less origin, matching its canonical / `og:url` / JSON-LD.
 */
const sitemap = (): MetadataRoute.Sitemap => {
  const lastmod: Record<string, string> = lastmodMap;

  return collectRoutes(APP_DIR).map(({ route }) => ({
    url: route === '/' ? websiteUrl : `${websiteUrl}${route}`,
    lastModified: lastmod[route],
    changeFrequency: 'monthly',
    priority: priorityFor(route)
  }));
};

export default sitemap;
